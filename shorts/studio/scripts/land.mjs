// Builds kit/land-dots.js: the dot grid for the dot-matrix globe, one dot per land cell.
// Rows every STEP degrees of latitude; within a row dots are spaced evenly on the sphere.
import {readFileSync, writeFileSync} from 'node:fs';
import {feature} from 'topojson-client';
import {geoContains, geoBounds} from 'd3-geo';

const STEP = 0.75;
const topo = JSON.parse(readFileSync('node_modules/world-atlas/land-110m.json', 'utf8'));
const land = feature(topo, topo.objects.land);
const polys = land.features.flatMap((f) =>
	f.geometry.type === 'MultiPolygon'
		? f.geometry.coordinates.map((c) => ({type: 'Polygon', coordinates: c}))
		: [f.geometry],
).map((g) => ({g, b: geoBounds(g)}));

const inBounds = ([lon, lat], [[x0, y0], [x1, y1]]) =>
	lat >= y0 && lat <= y1 && (x0 <= x1 ? lon >= x0 && lon <= x1 : lon >= x0 || lon <= x1);

const out = [];
for (let lat = -84; lat <= 84; lat += STEP) {
	const lonStep = STEP / Math.max(0.05, Math.cos((lat * Math.PI) / 180));
	const offset = (Math.round(lat / STEP) % 2) * lonStep * 0.5;
	for (let lon = -180 + offset; lon < 180; lon += lonStep) {
		const p = [lon, lat];
		if (polys.some(({g, b}) => inBounds(p, b) && geoContains(g, p))) {
			out.push(lat.toFixed(2), lon.toFixed(2));
		}
	}
}
writeFileSync('kit/land-dots.js', `// Generated by scripts/land.mjs from world-atlas land-110m.\nwindow.LAND_DOTS = new Float32Array([${out.join(',')}]);\n`);
console.log(`${out.length / 2} land dots`);
