// Builds dist/<name>/index.html from src/<name>.html + src/<name>.timing.json. Each short gets
// its own HyperFrames project folder (HyperFrames looks for index.html) that links back to the
// shared kit, vendor and assets folders.
// The timing file is the single source of truth for when things happen: captions, scene
// anchors and sound cues all come from it, so retiming to a voiceover is one JSON edit.
import {existsSync, mkdirSync, readFileSync, symlinkSync, writeFileSync} from 'node:fs';

const names = process.argv.slice(2).length ? process.argv.slice(2) : ['gravity', 'falling'];
for (const name of names) {
	const src = readFileSync(`src/${name}.html`, 'utf8');
	const timing = JSON.parse(readFileSync(`src/${name}.timing.json`, 'utf8'));
	const audio = [];
	if (timing.vo) {
		audio.push(`<audio id="vo" class="clip" data-start="0" data-duration="${timing.duration}" data-volume="1" src="${timing.vo}"></audio>`);
	}
	(timing.sfx || []).forEach((s, i) => {
		audio.push(
			`<audio id="sfx-${i + 1}" class="clip" data-start="${s.at}" data-duration="${s.dur}" data-volume="${s.vol ?? 0.8}" src="assets/sfx/${s.file}"></audio>`,
		);
	});
	const out = src
		.replace('<!doctype html>', `<!doctype html>\n<!-- Generated by scripts/build.mjs from src/${name}.html and src/${name}.timing.json. Edit those, then rebuild. -->`)
		.replaceAll('{{DURATION}}', String(timing.duration))
		.replace('<!-- @timing -->', `<script>window.TIMING = ${JSON.stringify(timing)};</script>`)
		.replace('<!-- @audio -->', audio.join('\n      '));
	const dir = `dist/${name}`;
	mkdirSync(dir, {recursive: true});
	for (const shared of ['kit', 'vendor', 'assets']) {
		if (!existsSync(`${dir}/${shared}`)) symlinkSync(`../../${shared}`, `${dir}/${shared}`);
	}
	writeFileSync(`${dir}/index.html`, out);
	console.log(`built ${dir}/index.html (${(timing.sfx || []).length} sound cues)`);
}
